export const workbookGuides = home.map((button) => {
  const m = modules[button.page];
  const fallback =
    m?.type === "stock"
      ? m.readOnly
        ? {
            ...report,
            steps: [
              "اختر الفترة والصنف والمخزن أو الثلاجة.",
              "راجع الكمية الواردة والصادرة والباقي ومتوسط التكلفة وقيمة الرصيد.",
              "تغيير الرصيد يتم بتسجيل أو تصحيح إذن المخزون الأصلي، ثم إعادة عرض التقرير.",
            ],
            related: ["stock-receipt", "stock-issue", "items"],
          }
        : stock
      : m?.type === "cost"
        ? cost
        : m?.type === "journal"
          ? journal
          : m?.type === "register"
            ? register
            : report;
  return {
    ...button,
    href: `/dashboard/${button.group}/${button.page}`,
    guide: specific[button.page] || fallback,
  };
});
export function workbookPage(route: string) {
  const path = route
    .split(/[?#]/)[0]
    .replace(/^\/(ar|en)(?=\/)/, "")
    .replace(/\/$/, "");
  return workbookGuides.find(
    (p) => p.href === path || `${p.group}/${p.page}` === path,
  );
}
